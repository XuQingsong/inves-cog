def test_cboe_pc_csv_parse():
    from inves_cog.flows.backfill import parse_cboe_pc_csv

    text = (
        "Total Exchange Volume and Open Interest\nGenerated by SDR\n"
        "DATE,CALL(S),PUT(S),TOTAL,P/C Ratio\n"
        "10/04/2019, 1000, 2000, 3000, 0.5\n"
    )
    rows = parse_cboe_pc_csv(text, "total")
    assert rows[0]["series_id"] == "cboe_pc_total" and rows[0]["value"] == 0.5
    assert rows[0]["obs_date"] == date(2019, 10, 4)


def test_finra_year_month_parse():
    # _xlsx_date fix: "2026-09" → month end
    from datetime import date as _date
    from datetime import timedelta

    y, mo = map(int, "2026-09".split("-"))
    m = _date(y, mo + 1 if mo < 12 else 1, 1) - timedelta(days=1)
    assert m == date(2026, 9, 30)


